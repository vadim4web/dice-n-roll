import assert from 'node:assert/strict';
import { initialProgress,restoreProgress,ensureDay,applyProgress,todayProgress } from '../src/game/progress.js';
import { initialGame,rollGame,dropGame,lockTile } from '../src/game/session.js';
const now=new Date('2026-10-26T12:00:00Z').getTime(),opts={random:()=>0,now};
const p=initialProgress(now);
assert.equal(p.wallet,120);assert.equal(ensureDay(p,now).granted,0);
const game=initialGame({...opts,wallet:p.wallet});
const roll=rollGame(game,opts);assert.equal(applyProgress(p,game,roll,now),true);
assert.equal(p.wallet,114);assert.equal(p.spentDice,6);
assert.equal(applyProgress(p,game,roll,now),false);assert.equal(p.spentDice,6);
const win=dropGame(game,opts);applyProgress(p,game,win,now);
assert.equal(p.wallet,2131);assert.equal(p.collection['six-kind'],1);assert.equal(p.earnedDice,2018);
assert.equal(todayProgress(p,now).netDice,2011);assert.equal(todayProgress(p,now).grant,120);
assert.deepEqual(p.pairs['1:1'],{attempts:12,hits:6});
const reloaded=restoreProgress(JSON.parse(JSON.stringify(p)),now);
assert.equal(ensureDay(reloaded,now).granted,0);assert.equal(reloaded.wallet,2131);
const newTable=initialGame({...opts,now:now+1,wallet:reloaded.wallet});
assert.equal(newTable.diceCredits,2131);assert.equal(reloaded.collection['six-kind'],1);
const lock=lockTile(newTable,'lower',0,3,{now:now+1});applyProgress(reloaded,newTable,lock,now);
assert.equal(reloaded.wallet,2129);assert.equal(reloaded.spentDice,9);
assert.equal(ensureDay(reloaded,now+86400000).granted,120);
assert.equal(ensureDay(reloaded,now+86400000).granted,0);
assert.equal(reloaded.wallet,2249);assert.equal(todayProgress(reloaded,now+86400000).earnedDice,0);
assert.equal(todayProgress(reloaded,now).earnedDice,2018);
const old=initialProgress(now,[{sessionId:'old',combinationCounts:{pair:3}},{id:'old',metrics:{combinationCounts:{pair:3}}}]);
assert.equal(old.collection.pair,3);assert.equal(old.wallet,120);
assert.equal(restoreProgress({schema:4,wallet:-1},now).wallet,120);
assert.equal(restoreProgress({...p,days:{bad:{earnedDice:'x'}}},now).wallet,120);
assert.equal(restoreProgress({...p,pairs:{'1:1':{attempts:1,hits:2}}},now).wallet,120);
console.log('Persistent progress checks passed: daily grant once, single wallet, idempotent earnings, lifetime collection, pair counts and legacy import.');
