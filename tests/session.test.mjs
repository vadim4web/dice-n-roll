import assert from 'node:assert/strict';
import { initialGame,restoreGame,rollGame,dropGame,lockTile,unlockTile,setTarget,checkpointGame,analyzeSession,finishGame } from '../src/game/session.js';
import { economy } from '../src/game/engine.js';
const opts={random:()=>0,now:1000};
const game=initialGame(opts);
assert.equal(game.diceCredits,120);
assert.equal(game.rollsLeft,undefined);
const lower=game.lower.map(t=>t.id);
const result=rollGame(game,opts);
assert.equal(result.cost,6);assert.equal(result.earnedDice,0);assert.equal(game.diceCredits,114);assert.equal(game.rolls,1);
assert.deepEqual(game.lower.map(t=>t.id),lower);
assert.equal(game.spentDice,6);
assert.deepEqual(game.metrics.pairs['1:1'],{attempts:6,hits:0});
const jackpot=dropGame(game,opts);
assert.equal(jackpot.combo.id,'six-kind');assert.equal(jackpot.earnedDice,2018);assert.equal(jackpot.netDice,2017);
assert.equal(game.diceCredits,2131);assert.equal(game.total,2018);
assert.deepEqual(game.metrics.pairs['1:1'],{attempts:12,hits:6});
const again=dropGame(game,opts);assert.equal(again.earnedDice,0);assert.equal(game.diceCredits,2130);
const summary=analyzeSession(game,5000);
assert.equal(summary.netDice,2010);assert.equal(summary.spentDice,8);assert.equal(summary.combinationCounts['six-kind'],1);
assert.equal(summary.lucky[0].key,'1:1');assert.equal(summary.lucky[0].attempts,12);assert.equal(summary.lucky[0].hits,6);
const frozen=initialGame(opts);
const oldUpper=frozen.upper.map(t=>t.id);
assert.equal(lockTile(frozen,'upper',1,1,opts).cost,1);
const lockQuote=economy(frozen),lockedRoll=rollGame(frozen,opts);
assert.equal(lockedRoll.cost,lockQuote.rollCost);
assert.equal(lockedRoll.ardor,lockQuote.ardor);
assert.equal(frozen.upper[1].id,oldUpper[1]);assert.equal(frozen.upper[1].lockRemaining,0);
assert.equal(frozen.diceCredits,120-1-lockQuote.rollCost);
const three=initialGame(opts);
for(const i of [0,2,4])lockTile(three,'lower',i,3,opts);
assert.equal(three.diceCredits,114);
assert.equal(economy(three).dropCost,3);
const before=three.lower.map(t=>t.id),paid=dropGame(three,{random:()=>.5,now:2000,automatic:true});
assert.equal(paid.cost,3);assert.equal(three.diceCredits,111);assert.equal(three.lower[0].id,before[0]);assert.equal(three.lower[2].id,before[2]);assert.equal(three.lower[4].id,before[4]);
assert.equal(three.lower[0].lockRemaining,2);assert.equal(three.metrics.automaticDrops,1);
assert.equal(three.events.at(-1).details.automatic,true);
const broke=initialGame({...opts,wallet:5});
const beforeBlocked=JSON.stringify(broke);
assert.equal(rollGame(broke,opts).reason,'no-dice');assert.equal(JSON.stringify(broke),beforeBlocked);
const zero=initialGame({...opts,wallet:1});
dropGame(zero,{random:()=>.5,now:2000});assert.equal(zero.phase,'finished');assert.equal(zero.diceCredits,0);
const all=initialGame(opts);all.upper.forEach(t=>t.lockRemaining=1);assert.equal(rollGame(all,opts).reason,'all-locked');unlockTile(all,'upper',0,opts);assert.equal(rollGame(all,opts).type,'roll');
const long=initialGame(opts);rollGame(long,opts);
for(let i=0;i<510;i++)checkpointGame(long,'pagehide',2000+i);
assert.equal(long.events.length,500);assert.equal(long.nextEventId,511);assert.equal(long.eventsDropped,11);
assert.equal(analyzeSession(long).actions,1);assert.equal(analyzeSession(long).pairs['1:1'].attempts,6);
const restored=restoreGame(JSON.parse(JSON.stringify(long)),opts);
assert.equal(restored.id,long.id);assert.equal(restored.diceCredits,114);
assert.equal(restoreGame({...long,diceCredits:-1},opts).diceCredits,120);
assert.equal(restoreGame({...long,nextEventId:12},opts).nextEventId,0);
const snap=JSON.stringify(game);analyzeSession(game);assert.equal(JSON.stringify(game),snap);
finishGame(game,'manual',6000);const count=game.nextEventId;finishGame(game,'manual',7000);assert.equal(game.nextEventId,count);
const endBalance=analyzeSession(game).balance;game.diceCredits+=120;game.grantedDice+=120;assert.equal(analyzeSession(game).balance,endBalance);
assert.equal(checkpointGame(game).type,'noop');assert.equal(rollGame(game).reason,'finished');
console.log('Wallet/session checks passed: real prices, coupled rewards, lock expiry, FIFO, no repeat payouts, pair statistics, bounded logs, restore and finish.');
