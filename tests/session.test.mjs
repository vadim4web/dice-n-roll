import assert from 'node:assert/strict';
import { initialGame, restoreGame, rollGame, bankGame, toggleDie } from '../src/game/session.js';
let now = 100000;
const values = [];
const options = () => ({ now, random: () => values.length ? (values.shift() - .5) / 6 : 0 });
const game = initialGame();
rollGame(game, options());
assert.equal(game.selected.length, 6);
bankGame(game, now);
assert.equal(game.total, 8000);
assert.equal(game.round, 2);
rollGame(game, options());
const hot = rollGame(game, options());
assert.equal(hot.hotDice, true);
assert.equal(game.turn, 8000);
assert.equal(game.held.length, 0);
values.push(2, 3, 4, 6, 2, 3);
assert.equal(rollGame(game, options()).type, 'bust');
assert.equal(game.turn, 0);
assert.equal(game.total, 8000);
rollGame(game, options());
assert.equal(game.round, 3);
toggleDie(game, 0, now);
assert.equal(game.selected.length, 5);
toggleDie(game, 0, now);
bankGame(game, now);
for (let round = 4; round <= 10; round++) { rollGame(game, options()); bankGame(game, now); }
assert.equal(game.phase, 'finished');
assert.equal(game.history.length, 10);
assert.equal(game.total, 72000);
bankGame(game, now);
assert.equal(game.total, 72000);
const blitz = initialGame('blitz');
rollGame(blitz, options());
assert.equal(blitz.deadline, now + 90000);
bankGame(blitz, now);
rollGame(blitz, options());
now += 90001;
assert.equal(bankGame(blitz, now).type, 'finished');
assert.equal(blitz.total, 8000);
assert.equal(blitz.turn, 0);
const held = initialGame();
values.push(1, 2, 3, 4, 6, 2);
rollGame(held, options());
assert.deepEqual(held.selected, [0]);
values.push(5, 2, 3, 4, 6);
rollGame(held, options());
assert.deepEqual(held.held, [0]);
assert.equal(held.dice[0], 1);
assert.equal(held.turn, 100);
assert.equal(toggleDie(held, 0, now), false);
bankGame(held, now);
assert.equal(held.total, 150);
assert.equal(restoreGame({ ...initialGame(), selected: [8] }).phase, 'ready');
assert.equal(restoreGame({ ...initialGame(), total: -1 }).total, 0);
assert.equal(restoreGame({ ...initialGame(), history: [{}] }).history.length, 0);
assert.equal(restoreGame(JSON.parse(JSON.stringify(game))).total, 72000);
console.log('Session tests passed: bank, hot dice, bust, held dice, selection, classic finish, blitz deadline, save validation.');
