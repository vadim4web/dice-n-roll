import assert from 'node:assert/strict';
import { initialGame, restoreGame, rollGame, dropGame, lockTile, unlockTile, setTarget, checkpointGame, analyzeSession, finishGame } from '../src/game/session.js';

const options = { random: () => 0, now: 1000 };
const game = initialGame(options);
assert.equal(game.upper.length, 6);
assert.equal(game.lower.length, 6);
assert.equal(game.rollsLeft, 50);
assert.equal(game.diceCredits, 12);
const beforeIds = game.upper.map(t => t.id);
const oldLower = game.lower.map(t => t.id);
const lockedId = game.upper[1].id;
assert.equal(lockTile(game, 'upper', 1, 1, { now: 1010 }).cost, 1);
assert.equal(game.diceCredits, 11);
const result = rollGame(game, { random: () => 0, now: 1100 });
assert.equal(result.type, 'roll');
assert.equal(game.rollsLeft, 49);
assert.equal(game.diceCredits, 17);
assert.equal(game.upper[1].id, lockedId);
assert.equal(game.upper[1].lockRemaining, 0);
assert(game.upper.filter((t, i) => i !== 1).every((t, i) => !beforeIds.includes(t.id)));
assert.deepEqual(game.lower.map(t => t.id), oldLower);
assert.equal(typeof result.probability, 'number');
assert.equal(typeof result.ardor, 'number');

assert.equal(lockTile(game, 'lower', 2, 3, { now: 1200 }).cost, 2);
const pinned = game.lower[2].id;
const dropBefore = game.lower.map(t => t.id);
const dropsBefore = game.diceCredits;
const drop = dropGame(game, { random: () => .5, now: 1300 });
assert.equal(drop.type, 'drop');
assert.equal(game.diceCredits, dropsBefore - 1);
assert.equal(game.lower[2].id, pinned);
assert.equal(game.lower[2].lockRemaining, 2);
assert.deepEqual(game.lower.slice(0, 2).map(t => t.id), [dropBefore[1], dropBefore[3]]);
assert.equal(game.lower.at(-1).id, drop.insertedId);

const scoring = initialGame(options);
scoring.upper.forEach((tile, i) => { tile.a = 1; tile.b = 1; tile.suit = i % 4; });
scoring.lower.forEach(tile => { tile.a = 1; tile.b = 1; });
scoring.awardedUpperIds = [];
const first = dropGame(scoring, options);
assert.equal(first.newMatches.length, 6);
assert(first.points > 0);
const firstTotal = scoring.total;
const duplicate = dropGame(scoring, options);
assert.equal(duplicate.points, 0);
assert.equal(scoring.total, firstTotal);

const allLocked = initialGame(options);
allLocked.upper.forEach(tile => { tile.lockRemaining = 1; });
const noCreditFarm = rollGame(allLocked, options);
assert.equal(noCreditFarm.reason, 'all-locked');
assert.equal(allLocked.diceCredits, 12);
assert.equal(unlockTile(allLocked, 'upper', 0, { now: 1400 }).cost, 0);
assert.equal(rollGame(allLocked, options).type, 'roll');
allLocked.lower.forEach(tile => { tile.lockRemaining = 3; });
assert.equal(dropGame(allLocked, options).reason, 'all-locked');
assert.equal(unlockTile(allLocked, 'lower', 0).cost, 0);
assert.equal(dropGame(allLocked, options).type, 'drop');

assert.equal(setTarget(game, 'straight').type, 'target');
assert.equal(game.target, 'straight');
assert.equal(setTarget(game, 'imaginary').type, 'blocked');
const noRolls = initialGame(options);
noRolls.rollsLeft = 1;
rollGame(noRolls, options);
assert.equal(noRolls.phase, 'active');
assert.equal(noRolls.rollsLeft, 0);
assert.equal(noRolls.diceCredits, 18);
assert.equal(rollGame(noRolls, options).reason, 'no-rolls');
assert.equal(dropGame(noRolls, options).type, 'drop');

const restored = restoreGame(JSON.parse(JSON.stringify(game)), options);
assert.equal(restored.id, game.id);
assert.equal(restored.events.length, game.events.length);
assert.equal(restoreGame({ ...game, upper: [] }, options).rollsLeft, 50);
assert.equal(restoreGame({ ...game, diceCredits: -1 }, options).diceCredits, 12);
const beforeAnalysis = JSON.stringify(game);
const analysis = analyzeSession(game, 5000);
assert.equal(JSON.stringify(game), beforeAnalysis);
assert.equal(analysis.actions, 2);
assert.equal(analysis.rolls, 1);
assert.equal(analysis.drops, 1);
assert.equal(analysis.spentOnLocks, 3);
assert.equal(analysis.durationMs, 4000);
const ended = finishGame(game, 'manual', 6000);
assert.equal(game.phase, 'finished');
assert.equal(ended.reason, 'manual');
const eventCount = game.events.length;
finishGame(game, 'manual', 9000);
assert.equal(game.events.length, eventCount);
assert.equal(rollGame(game, options).reason, 'finished');
const longLog = initialGame(options);
rollGame(longLog, options);
for (let i = 0; i < 510; i++) setTarget(longLog, i % 2 ? 'pair' : 'straight', { now: 2000 + i });
assert.equal(longLog.events.length, 500);
assert.equal(new Set(longLog.events.map(entry => entry.id)).size, 500);
assert.equal(analyzeSession(longLog).actions, 1);
assert.equal(longLog.eventsDropped, 11);
const checkpoints = initialGame(options);
rollGame(checkpoints, options);
const metricsBeforeCheckpoint = JSON.stringify(checkpoints.metrics);
for (let i = 0; i < 510; i++) checkpointGame(checkpoints, 'visibilitychange', 3000 + i);
assert.equal(checkpoints.events.length, 500);
assert.equal(checkpoints.eventsDropped, 11);
assert.equal(checkpoints.nextEventId, 511);
assert.equal(new Set(checkpoints.events.map(entry => entry.id)).size, 500);
assert.equal(JSON.stringify(checkpoints.metrics), metricsBeforeCheckpoint);
const checkpointRoundtrip = restoreGame(JSON.parse(JSON.stringify(checkpoints)), options);
assert.equal(checkpointRoundtrip.nextEventId, 511);
assert.equal(checkpointRoundtrip.eventsDropped, 11);
assert.equal(analyzeSession(checkpointRoundtrip).actions, 1);
assert.equal(restoreGame({ ...checkpoints, nextEventId: 511.5 }, options).nextEventId, 0);
assert.equal(restoreGame({ ...checkpoints, nextEventId: 510 }, options).nextEventId, 0);
finishGame(checkpoints, 'manual', 5000);
const finishedCheckpointCount = checkpoints.events.length;
assert.equal(checkpointGame(checkpoints, 'pagehide', 6000).type, 'noop');
assert.equal(checkpoints.events.length, finishedCheckpointCount);
const finishedRestored = restoreGame(JSON.parse(JSON.stringify(checkpoints)), options);
const finishEventsBefore = finishedRestored.nextEventId;
finishGame(finishedRestored, 'manual', 7000);
assert.equal(finishedRestored.nextEventId, finishEventsBefore);
const automatic = initialGame(options);
const manual = initialGame(options);
const autoResult = dropGame(automatic, { ...options, automatic: true });
const manualResult = dropGame(manual, options);
assert.equal(automatic.diceCredits, 11);
assert.equal(automatic.diceCredits, manual.diceCredits);
assert.equal(autoResult.points, manualResult.points);
assert.equal(autoResult.probability, manualResult.probability);
assert.deepEqual(automatic.lower, manual.lower);
assert.equal(automatic.events.at(-1).details.automatic, true);
assert.equal(manual.events.at(-1).details.automatic, false);
assert.equal(analyzeSession(automatic).automaticDrops, 1);
assert.equal(analyzeSession(automatic).manualDrops, 0);
assert.equal(analyzeSession(manual).automaticDrops, 0);
assert.equal(analyzeSession(manual).manualDrops, 1);
const oldSchema3 = JSON.parse(JSON.stringify(manual));
delete oldSchema3.metrics.automaticDrops;
assert.equal(restoreGame(oldSchema3, options).id, manual.id);
assert.equal(restoreGame(oldSchema3, options).metrics.automaticDrops, 0);
assert.equal(oldSchema3.metrics.automaticDrops, undefined);
assert.equal(restoreGame({ ...manual, metrics: { ...manual.metrics, automaticDrops: .5 } }, options).drops, 0);
assert.equal(restoreGame({ ...manual, metrics: { ...manual.metrics, automaticDrops: -1 } }, options).drops, 0);
const onlyRoll = initialGame(options);
rollGame(onlyRoll, options);
assert.equal(analyzeSession(onlyRoll).playStyle, 'balanced');
assert.match(analyzeSession(onlyRoll).description, /выбирал полные броски/);
console.log('Session checks passed: independent Roll, FIFO Drop, paid locks, expiration, no duplicate rewards, resource accounting, restore, immutable analysis and idempotent finish.');
